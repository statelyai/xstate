// Type-error-quality benchmark.
//
// Compiles the deliberately-broken fixtures in scripts/type-error-fixtures/
// (each contains exactly one realistic mistake) and snapshots the compiler
// output to scripts/type-error-quality.out.md. Error output is API surface:
// review the snapshot in PRs the same way you review types.
//
// Usage:
//   node scripts/type-error-quality.mjs          # regenerate the snapshot
//   node scripts/type-error-quality.mjs --check  # fail if output differs from it

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fixturesDir = join(root, 'scripts', 'type-error-fixtures');
const tsc = join(root, 'node_modules', '.bin', 'tsc');
const snapshotPath = join(root, 'scripts', 'type-error-quality.out.md');
const check = process.argv.includes('--check');
const fixtures = readdirSync(fixturesDir).filter((f) => f.endsWith('.ts'));

// A negative fixture is useful only when repairing its intended mistake makes
// it valid. Check the corrected sources in memory so obsolete syntax or a
// second error cannot silently become the diagnostic baseline.
const require = createRequire(import.meta.url);
const ts = require('typescript');
const repairs = JSON.parse(
  readFileSync(join(fixturesDir, 'repairs.json'), 'utf8')
);
const fixedSources = new Map();
for (const fixture of fixtures) {
  const repair = repairs[fixture];
  if (!repair || repair.length !== 2) {
    throw new Error(`Missing diagnostic repair for ${fixture}`);
  }
  const file = join(fixturesDir, fixture);
  const source = readFileSync(file, 'utf8');
  const [before, after] = repair;
  if (
    !before ||
    source.indexOf(before) < 0 ||
    source.indexOf(before) !== source.lastIndexOf(before)
  ) {
    throw new Error(`Diagnostic repair must match exactly once in ${fixture}`);
  }
  fixedSources.set(file, source.replace(before, after));
}
const config = ts.readConfigFile(
  join(fixturesDir, 'tsconfig.json'),
  ts.sys.readFile
);
if (config.error)
  throw new Error(
    ts.flattenDiagnosticMessageText(config.error.messageText, '\n')
  );
const parsed = ts.parseJsonConfigFileContent(
  config.config,
  ts.sys,
  fixturesDir
);
const host = ts.createCompilerHost(parsed.options);
const readFile = host.readFile.bind(host);
host.readFile = (file) => fixedSources.get(file) ?? readFile(file);
const repairedProgram = ts.createProgram(
  parsed.fileNames,
  parsed.options,
  host
);
const repairErrors = [
  ...parsed.errors,
  ...ts.getPreEmitDiagnostics(repairedProgram)
];
if (repairErrors.length) {
  console.error(
    ts.formatDiagnosticsWithColorAndContext(repairErrors, {
      getCurrentDirectory: () => root,
      getCanonicalFileName: (file) => file,
      getNewLine: () => '\n'
    })
  );
  throw new Error(
    'Corrected type-error fixtures must compile without diagnostics.'
  );
}
console.log(`${fixtures.length} corrected diagnostic fixtures compile.`);

let raw = '';
const start = Date.now();
try {
  raw = execFileSync(tsc, ['-p', fixturesDir, '--pretty', 'false'], {
    cwd: root,
    encoding: 'utf8'
  });
} catch (err) {
  raw = (err.stdout ?? '') + (err.stderr ?? '');
}
const elapsed = ((Date.now() - start) / 1000).toFixed(1);

const byFixture = Object.fromEntries(fixtures.map((f) => [f, []]));
let current = null;
for (const line of raw.split('\n')) {
  const m = line.match(/type-error-fixtures\/([\w.]+\.ts)\(/);
  if (m) current = m[1];
  else if (!/^\s/.test(line)) current = null;
  if (current && byFixture[current]) byFixture[current].push(line);
}

let out = `# Type-error-quality snapshot\n\nGenerated by \`node scripts/type-error-quality.mjs\`.\nEach fixture contains exactly one realistic mistake; below is the complete\ncompiler output a user would see for it.\n`;
let missing = false;
for (const f of fixtures) {
  const lines = byFixture[f];
  out += `\n## ${f}\n\n`;
  if (lines.length === 0) {
    out += `**NO ERROR REPORTED — the mistake compiles cleanly. This is a soundness gap.**\n`;
    missing = true;
  } else {
    out += '```\n' + lines.join('\n') + '\n```\n';
  }
}
if (check) {
  if (readFileSync(snapshotPath, 'utf8') !== out) {
    console.log(out);
    console.error(
      '\nType-error output differs from scripts/type-error-quality.out.md.' +
        '\nRun `pnpm bench:type-errors` and review the snapshot diff.'
    );
    process.exitCode = 1;
  } else {
    console.log(
      `Type-error output matches the snapshot (tsc took ${elapsed}s).`
    );
  }
} else {
  writeFileSync(snapshotPath, out);
  console.log(out);
  console.log(
    `Snapshot written to scripts/type-error-quality.out.md (tsc took ${elapsed}s)`
  );
}
if (missing) {
  console.error('\nAt least one fixture produced no compile error.');
  process.exitCode = 1;
}
